def answer(question, state=None):
    """返回 dict(reply, topic)。state 可注入 /api/state 结果。"""
    q = (question or '').strip()
    for topic, keys in TOPICS:
        if any(k.lower() in q.lower() for k in keys):
            if topic == '状态' and state:
                return dict(topic=topic, reply=(
                    f"当前状态：数据更新至 {state.get('data_through') or '未知'}；"
                    f"选股日 P={state.get('p_day') or '—'}、监控日 D={state.get('monitor_day') or '—'}；"
                    f"选股模型 {'开' if (state.get('model_switch') or {}).get('selection') else '关'}；"
                    f"数据源 {(state.get('source') or {}).get('source', 'tdx')}；"
                    f"最近运行 {state.get('latest_run') or '（尚未运行）'}。"))
            return dict(topic=topic, reply=ANSWERS[topic])
    return dict(topic=None, reply=FALLBACK)
